"""Separamos las variables predictoras y la variable objetivo"""

import numpy as np

# Separar predictores y variable objetivo
X_train = data_entrenamiento.drop(columns="Outcome").copy()
y_train = data_entrenamiento["Outcome"]

X_test = data_evaluacion.drop(columns="Outcome").copy()
y_test = data_evaluacion["Outcome"]

X_produccion = data_produccion.drop(columns="Outcome").copy()

# Columnas donde cero representa un posible faltante
columnas_ceros = [
    "Glucose",
    "BloodPressure",
    "SkinThickness",
    "Insulin",
    "BMI"
]

# Reemplazar ceros por NaN en los tres conjuntos
for conjunto in [X_train, X_test, X_produccion]:
    conjunto[columnas_ceros] = conjunto[columnas_ceros].replace(0, np.nan)

# Comprobar el reemplazo en entrenamiento
print(X_train[columnas_ceros].isna().sum())

"""Creación del pipeline de preparación"""

from sklearn.pipeline import Pipeline
from sklearn.compose import ColumnTransformer
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import StandardScaler

columnas_ceros = [
    "Glucose",
    "BloodPressure",
    "SkinThickness",
    "Insulin",
    "BMI"
]

otras_columnas = [
    c for c in X_train.columns if c not in columnas_ceros
]

preprocesamiento = ColumnTransformer([
    ("imputacion", SimpleImputer(
    strategy="median"
), columnas_ceros),

    ("otras", "passthrough", otras_columnas)
])

pipeline_preparacion = Pipeline([
    ("preprocesamiento", preprocesamiento),
    ("escalado", StandardScaler())
])

"""\* Indicamos qué variables contienen ceros que podrían representar datos faltantes.


* Preparamos su reemplazo mediante la mediana.


* Incorporamos una estandarización para los modelos que la necesiten.


* Dejamos todas las transformaciones dentro de un pipeline.
"""

pipeline_preparacion_A = pipeline_preparacion

# Alternativa B: excluir solamente Insulin

columnas_ceros_B = [
    "Glucose",
    "BloodPressure",
    "SkinThickness",
    "BMI"
]

otras_columnas_B = [
    "Pregnancies",
    "DiabetesPedigreeFunction",
    "Age"
]

preprocesamiento_B = ColumnTransformer([
    ("imputacion", SimpleImputer(
        strategy="median"
    ), columnas_ceros_B),

    ("otras", "passthrough", otras_columnas_B)
])

pipeline_preparacion_B = Pipeline([
    ("preprocesamiento", preprocesamiento_B),
    ("escalado", StandardScaler())
])

from sklearn.base import clone
from sklearn.model_selection import StratifiedKFold, cross_validate
from sklearn.pipeline import Pipeline
from sklearn.linear_model import LogisticRegression
from sklearn.neighbors import KNeighborsClassifier
from sklearn.svm import SVC
from sklearn.ensemble import RandomForestClassifier, GradientBoostingClassifier

# Validación cruzada: conserva aproximadamente la proporción de Outcome
cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)

modelos = {
    "Regresión logística": LogisticRegression(max_iter=2000, class_weight="balanced"),
    "K vecinos (KNN)": KNeighborsClassifier(n_neighbors=5),
    "SVM": SVC(class_weight="balanced", probability=True),
    "Random Forest": RandomForestClassifier(
        n_estimators=300,
        random_state=42,
        class_weight="balanced"
    ),
    "Gradient Boosting": GradientBoostingClassifier(random_state=42)
}

preprocesamientos = {
    "A (imputa ceros de Insulin)": pipeline_preparacion_A,
    "B (excluye Insulin)": pipeline_preparacion_B
}

resultados = []

for nombre_prep, prep in preprocesamientos.items():
    for nombre_modelo, modelo in modelos.items():
        pipeline = Pipeline([
            ("preparacion", clone(prep)),
            ("modelo", clone(modelo))
        ])

        scores = cross_validate(
            pipeline,
            X_train,
            y_train,
            cv=cv,
            scoring={
                "f1": "f1",
                "recall": "recall",
                "precision": "precision",
                "roc_auc": "roc_auc",
                "accuracy": "accuracy"
            },
            n_jobs=-1
        )

        resultados.append({
            "Preprocesamiento": nombre_prep,
            "Modelo": nombre_modelo,
            "F1 promedio": scores["test_f1"].mean(),
            "Recall promedio": scores["test_recall"].mean(),
            "Precisión promedio": scores["test_precision"].mean(),
            "ROC AUC promedio": scores["test_roc_auc"].mean(),
            "Accuracy promedio": scores["test_accuracy"].mean()
        })

tabla_resultados = (
    pd.DataFrame(resultados)
    .sort_values("F1 promedio", ascending=False)
    .reset_index(drop=True)
)

tabla_resultados.round(3)

from sklearn.metrics import (
    classification_report,
    confusion_matrix,
    ConfusionMatrixDisplay,
    roc_auc_score
)
import matplotlib.pyplot as plt

mejor_fila = tabla_resultados.iloc[0]
nombre_prep = mejor_fila["Preprocesamiento"]
nombre_modelo = mejor_fila["Modelo"]

mejor_prep = preprocesamientos[nombre_prep]
mejor_modelo = modelos[nombre_modelo]

modelo_final = Pipeline([
    ("preparacion", clone(mejor_prep)),
    ("modelo", clone(mejor_modelo))
])

modelo_final.fit(X_train, y_train)
y_pred = modelo_final.predict(X_test)

print(f"Modelo: {nombre_modelo}")
print(f"Preprocesamiento: {nombre_prep}")
print("\nReporte de clasificación:")
print(classification_report(y_test, y_pred, target_names=["Sin diabetes", "Con diabetes"]))

print("Matriz de confusión:")
print(confusion_matrix(y_test, y_pred))

if hasattr(modelo_final, "predict_proba"):
    y_prob = modelo_final.predict_proba(X_test)[:, 1]
    print("ROC AUC en prueba:", round(roc_auc_score(y_test, y_prob), 3))

ConfusionMatrixDisplay.from_predictions(
    y_test,
    y_pred,
    display_labels=["Sin diabetes", "Con diabetes"],
    cmap="Blues"
)
plt.show()