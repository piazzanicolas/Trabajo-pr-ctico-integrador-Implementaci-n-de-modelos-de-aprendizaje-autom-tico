"""Los registros con Outcome = 1 presentan, en promedio, valores más elevados de glucosa, IMC y edad. Aunque los promedios todavía incluyen los 0

Separar entrenamiento y evaluación
"""

data_entrenamiento, data_evaluacion = train_test_split(
    data_desarrollo,
    test_size=0.20,
    random_state=1234,
    stratify=data_desarrollo["Outcome"]
)

print("Entrenamiento:", data_entrenamiento.shape)
print("Evaluación:", data_evaluacion.shape)
print("Producción:", data_produccion.shape)

"""Separamos las variables predictoras y la variable objetivo"""

# Separar predictores y variable objetivo
X_train = data_entrenamiento.drop(columns="Outcome").copy()
y_train = data_entrenamiento["Outcome"]

X_test = data_evaluacion.drop(columns="Outcome").copy()
y_test = data_evaluacion["Outcome"]

X_produccion = data_produccion.drop(columns="Outcome").copy()

# Columnas donde cero representa un posible faltante
columnas_ceros = [
    "Glucose",
    "BloodPressure",
    "SkinThickness",
    "Insulin",
    "BMI"
]

# Reemplazar ceros por NaN en los tres conjuntos
for conjunto in [X_train, X_test, X_produccion]:
    conjunto[columnas_ceros] = conjunto[columnas_ceros].replace(0, np.nan)

# Comprobar el reemplazo en entrenamiento
print(X_train[columnas_ceros].isna().sum())

"""Creación del pipeline de preparación"""

from sklearn.pipeline import Pipeline
from sklearn.compose import ColumnTransformer
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import StandardScaler

columnas_ceros = [
    "Glucose",
    "BloodPressure",
    "SkinThickness",
    "Insulin",
    "BMI"
]

otras_columnas = [
    c for c in X_train.columns if c not in columnas_ceros
]

preprocesamiento = ColumnTransformer([
    ("imputacion", SimpleImputer(
    strategy="median"
), columnas_ceros),

    ("otras", "passthrough", otras_columnas)
])

pipeline_preparacion = Pipeline([
    ("preprocesamiento", preprocesamiento),
    ("escalado", StandardScaler())
])

"""\* Indicamos qué variables contienen ceros que podrían representar datos faltantes.


* Preparamos su reemplazo mediante la mediana.


* Incorporamos una estandarización para los modelos que la necesiten.

* Incorporamos la imputación de valores faltantes y la estandarización dentro de un pipeline. El reemplazo de ceros por NaN se realiza previamente
"""

pipeline_preparacion_A = pipeline_preparacion

# Alternativa B: excluir solamente Insulin

columnas_ceros_B = [
    "Glucose",
    "BloodPressure",
    "SkinThickness",
    "BMI"
]

otras_columnas_B = [
    "Pregnancies",
    "DiabetesPedigreeFunction",
    "Age"
]

preprocesamiento_B = ColumnTransformer([
    ("imputacion", SimpleImputer(
        strategy="median"
    ), columnas_ceros_B),

    ("otras", "passthrough", otras_columnas_B)
])

pipeline_preparacion_B = Pipeline([
    ("preprocesamiento", preprocesamiento_B),
    ("escalado", StandardScaler())
])

"""## 3. Modelado

En esta etapa continuamos con las particiones que armamos anteriormente: 521 registros para entrenamiento, 131 para evaluación y 116 reservados para simular producción. El último lote se mantiene sin usar hasta la etapa de monitoreo.

Como queremos reconocer la mayor cantidad posible de casos positivos, prestamos especial atención al **recall** y a los falsos negativos. También miramos **F1**, que nos ayuda a considerar conjuntamente la precisión y el recall. Además usamos F2 en la búsqueda de hiperparámetros para darle mayor peso a la detección de casos positivos. La accuracy no se toma como criterio principal.

### 3.1. Preparación de los datos y casos con cero

En el análisis inicial vimos ceros en `Glucose`, `BloodPressure`, `SkinThickness`, `Insulin` y `BMI`. En estas variables un cero puede indicar un dato faltante o mal registrado. En cambio, cero embarazos (`Pregnancies = 0`) es un valor posible, por lo que no se reemplaza. La variable objetivo `Outcome = 0` tampoco se cambia.

Los ceros se reemplazan por NaN después de dividir los datos. Luego, el pipeline calcula las medianas utilizando solamente el conjunto de entrenamiento y las aplica a los datos de evaluación.

Nos interesa probar las dos preparaciones que ya habíamos planteado: **A**, que reemplaza los ceros de `Insulin`, y **B**, que excluye `Insulin`. Como casi la mitad de los registros tiene cero en esa columna, vamos a comparar las dos opciones antes de elegir.
"""

# Revisamos cuántos ceros hay en las variables de interés.
ceros = (data_desarrollo[columnas_ceros] == 0).sum().sort_values(ascending=False)
porcentajes = (ceros / len(data_desarrollo) * 100).round(1)
st.dataframe(
    pd.DataFrame({
        "Ceros": ceros,
        "Porcentaje": porcentajes
    }),
    use_container_width=True
)
print("Conjuntos ya reservados:", len(X_train), "entrenamiento;", len(X_test), "evaluación;", len(data_produccion), "producción")

"""### 3.2. Línea base y comparación de modelos

Primero incluimos una línea base que predice siempre la clase más frecuente. Después comparamos una regresión logística y Random Forest, para probar dos formas distintas de modelar. Para cada una revisamos los hiperparámetros con `GridSearchCV` y cuatro particiones estratificadas. Todas las búsquedas usan únicamente entrenamiento; las transformaciones se ajustan dentro de cada partición.
"""

from sklearn.base import clone
from sklearn.dummy import DummyClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import StratifiedKFold, GridSearchCV
from sklearn.metrics import (precision_score, recall_score, f1_score,
                             fbeta_score, confusion_matrix, make_scorer)

validacion = StratifiedKFold(n_splits=4, shuffle=True, random_state=42)
metrica_busqueda = make_scorer(fbeta_score, beta=2, pos_label=1)
preparaciones = {"A - Imputar Insulin": pipeline_preparacion_A,
                 "B - Excluir Insulin": pipeline_preparacion_B}

configuraciones = {
    "Regresión logística": (
        LogisticRegression(max_iter=2000, random_state=42),
        {"modelo__C": [0.1, 1, 10], "modelo__class_weight": [None, "balanced"]}
    ),
    "Random Forest": (
        RandomForestClassifier(random_state=42, n_jobs=1, class_weight="balanced"),
        {"modelo__n_estimators": [100, 200],
         "modelo__max_depth": [4, 8, None],
         "modelo__min_samples_leaf": [2, 5]}
    )
}

busquedas = {}
filas_cv = []
for nombre, (algoritmo, parametros) in configuraciones.items():
    for nombre_prep, prep in preparaciones.items():
        modelo = Pipeline([
            ("preparacion", clone(prep)),
            ("modelo", clone(algoritmo))
        ])
        busqueda = GridSearchCV(modelo, parametros, scoring=metrica_busqueda,
                                 cv=validacion, n_jobs=-1)
        busqueda.fit(X_train, y_train)
        busquedas[(nombre, nombre_prep)] = busqueda
        filas_cv.append({"Modelo": nombre, "Preparación": nombre_prep,
                         "F2 validación": busqueda.best_score_,
                         "Parámetros": str({k.replace('modelo__',''):v for k,v in busqueda.best_params_.items()})})

resultados_cv = pd.DataFrame(filas_cv).sort_values(["Modelo", "F2 validación"], ascending=[True, False])
st.dataframe(resultados_cv.round(3), use_container_width=True)

"""### 3.3. Resultados de evaluación

Para no elegir el tratamiento de los ceros mirando los resultados de evaluación, primero nos quedamos con la preparación que obtuvo mejor F2 en validación cruzada para cada algoritmo. Recién después evaluamos esos dos modelos y la línea base sobre los 131 casos apartados.

La tabla muestra F1, recall, precisión, F2 y los dos tipos de error. Dejamos la accuracy fuera de la tabla principal porque no es suficiente para el objetivo del centro de salud.
"""

elegidos_por_algoritmo = {}
for nombre in configuraciones:
    opciones = [(n_prep, b) for (n_alg, n_prep), b in busquedas.items() if n_alg == nombre]
    mejor_prep, mejor_busqueda = max(opciones, key=lambda par: par[1].best_score_)
    elegidos_por_algoritmo[nombre] = (mejor_prep, mejor_busqueda)

linea_base = DummyClassifier(strategy="most_frequent")
linea_base.fit(X_train, y_train)
modelos_evaluacion = {"Línea base": linea_base}
for nombre, (prep, busqueda) in elegidos_por_algoritmo.items():
    modelos_evaluacion[nombre] = busqueda.best_estimator_

filas = []
predicciones = {}
matrices = {}
for nombre, modelo in modelos_evaluacion.items():
    pred = modelo.predict(X_test)
    predicciones[nombre] = pred
    matriz = confusion_matrix(y_test, pred, labels=[0, 1])
    matrices[nombre] = matriz
    tn, fp, fn, tp = matriz.ravel()
    filas.append({"Modelo": nombre,
                  "Precisión": precision_score(y_test, pred, zero_division=0),
                  "Recall": recall_score(y_test, pred, zero_division=0),
                  "F1": f1_score(y_test, pred, zero_division=0),
                  "F2": fbeta_score(y_test, pred, beta=2, zero_division=0),
                  "Falsos negativos": int(fn), "Falsos positivos": int(fp),
                  "Positivos detectados": int(tp)})

comparacion = pd.DataFrame(filas).set_index("Modelo")
st.dataframe(comparacion.round(3), use_container_width=True)
print("Preparaciones elegidas en entrenamiento:")
for nombre, (prep, b) in elegidos_por_algoritmo.items():
    print(f"{nombre}: {prep} | F2 validación: {b.best_score_:.3f}")

# Vemos en cada caso qué predijo el modelo y qué decía la base.
import matplotlib.pyplot as plt
fig, ejes = plt.subplots(1, 3, figsize=(12.6, 3.5))
for eje, (nombre, matriz) in zip(ejes, matrices.items()):
    eje.imshow(matriz, cmap="Blues")
    eje.set_title(nombre)
    eje.set_xlabel("Predicho")
    eje.set_ylabel("Real")
    eje.set_xticks([0, 1]); eje.set_yticks([0, 1])
    for i in range(2):
        for j in range(2):
            eje.text(j, i, str(matriz[i, j]), ha="center", va="center")
plt.tight_layout()
st.pyplot(fig)
plt.close(fig)

"""### 3.4. Análisis de errores

Para interpretar los errores miramos los valores originales de glucosa, IMC y edad en los casos mal clasificados. Estos promedios describen lo que encontramos en esta partición; no permiten explicar por sí solos una predicción ni sacar conclusiones clínicas.
"""

detalle_errores = []
for nombre in ["Regresión logística", "Random Forest"]:
    temp = X_test.copy()
    temp["Real"] = y_test
    temp["Predicho"] = predicciones[nombre]
    temp["Tipo de resultado"] = np.select(
        [(temp["Real"] == 1) & (temp["Predicho"] == 0),
         (temp["Real"] == 0) & (temp["Predicho"] == 1)],
        ["Falso negativo", "Falso positivo"], default="Acierto")
    for tipo in ["Falso negativo", "Falso positivo"]:
        casos = temp[temp["Tipo de resultado"] == tipo]
        detalle_errores.append({"Modelo": nombre, "Error": tipo,
                               "Cantidad": len(casos),
                               "Glucosa media": casos["Glucose"].mean(),
                               "IMC medio": casos["BMI"].mean(),
                               "Edad media": casos["Age"].mean()})
analisis_errores = pd.DataFrame(detalle_errores)
st.dataframe(analisis_errores.round(1), use_container_width=True)

"""### 3.5. Modelo propuesto

Tomamos la decisión con el resultado de validación cruzada y revisamos en evaluación si mantiene un comportamiento razonable. Le damos mayor importancia a los falsos negativos que a los falsos positivos, porque el modelo se usaría para orientar una evaluación posterior y no para realizar un diagnóstico. No elegimos por accuracy ni tocamos el lote de producción para esta decisión.
"""

# Elegimos por F2 de validación cruzada, no por el resultado del conjunto de evaluación.
modelo_elegido = max(elegidos_por_algoritmo,
                     key=lambda nombre: elegidos_por_algoritmo[nombre][1].best_score_)
preparacion_elegida, busqueda_elegida = elegidos_por_algoritmo[modelo_elegido]

print("Modelo propuesto:", modelo_elegido)
print("Preparación:", preparacion_elegida)
print("F2 validación:", round(busqueda_elegida.best_score_, 3))
print("F1 evaluación:", round(comparacion.loc[modelo_elegido, "F1"], 3))
print("Recall evaluación:", round(comparacion.loc[modelo_elegido, "Recall"], 3))
print("Falsos negativos:", int(comparacion.loc[modelo_elegido, "Falsos negativos"]))
print("Falsos positivos:", int(comparacion.loc[modelo_elegido, "Falsos positivos"]))
print("Lote de producción: reservado para el monitoreo posterior")
